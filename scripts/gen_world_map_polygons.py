"""Writes the town map's solids as polygons (data/world_map_collision_polygons.json).

The solid mask is built the same way as scripts/gen_world_map_collision.py (the road colours, the carved
lanes and the plaques), then each solid blob is outlined with OpenCV, the same method as the Forest
polygons. The walkable roads stay open. Run it after changing the road mask or the carves.
Usage: python scripts/gen_world_map_polygons.py
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).parent))
import gen_area_collision as area_tools  # noqa: E402  (polygon_solids: the blob outlines)
import gen_world_map_collision as world  # noqa: E402  (the same road mask and carves)

OUT = "data/world_map_collision_polygons.json"
SIMPLIFY_PX = 1.0  # tighter than the Forest outlines, so the roads stay as wide as the rectangles


def main():
    assert world.CELL == area_tools.CELL, "both generators must use the same cell size"
    im = np.asarray(Image.open(world.MAP).convert("RGB")).astype(int)
    h, w = im.shape[:2]
    walk = world.dilate(world.road_mask(im), 6)
    for x0, y0, cw, ch in world.CARVE:
        walk[y0:y0 + ch, x0:x0 + cw] = True
    for x0, y0, x1, y1 in world.PLAQUES:
        walk[y0:y1, x0:x1] = False
    # Lanes into the Town plaza from the road, beside the Town plaque (applied after it).
    for x0, y0, cw, ch in [(862, 600, 22, 110)]:
        walk[y0:y0 + ch, x0:x0 + cw] = True
    solid = ~walk

    cell = world.CELL
    ch_n, cw_n = h // cell, w // cell
    cells = solid[:ch_n * cell, :cw_n * cell].reshape(ch_n, cell, cw_n, cell).mean(axis=(1, 3)) > 0.5
    cells = world.majority(cells, 3)  # drop single-cell specks so they do not block the roads

    area_tools.SIMPLIFY_PX = SIMPLIFY_PX
    blobs = area_tools.polygon_solids(cells)
    solids = [{"id": f"solid_{i}", "loops": loops} for i, loops in enumerate(blobs)]
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({
            "_note": "Solid areas of the town map (assets/map/town_map.webp) as polygon loops, in image pixels. Generated by scripts/gen_world_map_polygons.py. Roads, the Town plaza, the beach sand and the beach path are walkable.",
            "solids": solids,
        }, f)
    print(f"{len(solids)} solid polygons written to {OUT}")


if __name__ == "__main__":
    main()

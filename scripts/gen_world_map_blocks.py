"""Writes the town map's collision as one rectangle per block (data/world_map_collision_blocks.json).

- Each place's block (its buildings, lawns and paths between the roads) is one solid rectangle touching the road.
- The map's outer border (outside the road ring) is four solid rectangles.
- Anything else that is not road (the sea, for example) is kept as polygons outlined from the mask.
- Roads, the Town plaza and the beach sand are walkable only where no block rectangle covers them.

The road mask and carves are the same as scripts/gen_world_map_collision.py. Usage: python scripts/gen_world_map_blocks.py
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).parent))
import gen_area_collision as area_tools  # noqa: E402  (polygon_solids: outlines of the remaining solids)
import gen_world_map_collision as world  # noqa: E402  (the same road mask and carves)

OUT = "data/world_map_collision_blocks.json"
# One rectangle per block, in map pixels (x, y, width, height). Each touches the road around it.
BLOCKS = {
    "temple": (135, 112, 315, 173),
    "forest": (488, 112, 840, 173),
    "viewpoint": (1358, 112, 217, 173),
    "lake": (133, 303, 328, 186),
    "home": (497, 300, 336, 189),
    "greenhouse": (869, 300, 272, 189),
    "farm": (1177, 300, 375, 186),  # ends above the Farm zone, which sits on the road at y 488
    "library": (133, 508, 334, 199),
    "town": (494, 503, 588, 200),
    "riverbank": (1095, 510, 457, 195),
    "college": (830, 718, 724, 162),
    "beach": (340, 745, 440, 120),  # the sand; the Beach zone is on the road strip above it
}
BLOCK_INSET = 4
# The outer road ring: rows 98..909 and columns 29..1628 hold the road. Outside it is the border.
ROAD_TOP, ROAD_BOTTOM, ROAD_LEFT, ROAD_RIGHT = 98, 909, 29, 1628


def main():
    area_tools.SIMPLIFY_PX = 1.0
    im = np.asarray(Image.open(world.MAP).convert("RGB")).astype(int)
    h, w = im.shape[:2]
    walk = world.dilate(world.road_mask(im), 6)
    for x0, y0, cw, ch in world.CARVE:
        walk[y0:y0 + ch, x0:x0 + cw] = True
    for x0, y0, x1, y1 in world.PLAQUES:
        walk[y0:y1, x0:x1] = False
    # Each place's entry strip (an 18 px road strip in locations.json) is walkable, so it can be reached.
    for location in json.loads(Path("data/locations.json").read_text(encoding="utf-8"))["locations"]:
        zone = location.get("zone")
        if zone and zone[3] == 18:
            zx, zy, zw, zh = zone
            walk[zy:zy + zh, zx:zx + zw] = True

    covered = np.zeros((h, w), bool)
    solids = []
    for name, (x, y, bw, bh) in BLOCKS.items():
        # Inset from the road edge, so she can turn the corners of a block without catching on them.
        x, y, bw, bh = x + BLOCK_INSET, y + BLOCK_INSET, bw - 2 * BLOCK_INSET, bh - 2 * BLOCK_INSET
        covered[y:y + bh, x:x + bw] = True
        solids.append({"id": f"block_{name}", "rect": [x, y, bw, bh]})

    border = {
        "border_top": (0, 0, w, ROAD_TOP),
        "border_bottom": (0, ROAD_BOTTOM + 1, w, h - ROAD_BOTTOM - 1),
        "border_left": (0, ROAD_TOP, ROAD_LEFT, ROAD_BOTTOM - ROAD_TOP + 1),
        "border_right": (ROAD_RIGHT + 1, ROAD_TOP, w - ROAD_RIGHT - 1, ROAD_BOTTOM - ROAD_TOP + 1),
    }
    for name, (x, y, bw, bh) in border.items():
        covered[y:y + bh, x:x + bw] = True
        solids.append({"id": name, "rect": [x, y, bw, bh]})

    # Whatever is still solid and not road: the sea and other terrain, outlined as polygons.
    remainder = (~walk) & (~covered)
    cell = world.CELL
    ch_n, cw_n = h // cell, w // cell
    cells = remainder[:ch_n * cell, :cw_n * cell].reshape(ch_n, cell, cw_n, cell).mean(axis=(1, 3)) > 0.5
    cells = world.majority(cells, 3)
    for i, loops in enumerate(area_tools.polygon_solids(cells)):
        solids.append({"id": f"terrain_{i}", "loops": loops})

    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({
            "_note": "Town map collision: one rectangle per block, the map border, and the terrain (the sea) as polygons. Generated by scripts/gen_world_map_blocks.py.",
            "solids": solids,
        }, f)
    rects = sum(1 for s in solids if "rect" in s)
    print(f"{rects} rectangles and {len(solids) - rects} terrain polygons written to {OUT}")


if __name__ == "__main__":
    main()

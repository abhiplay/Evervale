"""Trace the walkable ground on the town map and write data/world_map_collision.json.

Roads are grey asphalt. The Town plaza, the beach sand and the beach path are carved in
as walkable. Everything else (buildings, lawns, trees, water, rock) is solid.
Coordinates are image pixels; the map is used at scale 1 in the game.
The road shapes come from assets/map/town_map_roads.webp (same layout as the displayed map).
"""
import json
import numpy as np
from PIL import Image

# The road shapes are read from the flat version of the map. The darker picture shown in the
# game has the same layout, but its roofs and river edges look like road to the colour test.
MAP = "assets/map/town_map_roads.webp"
OUT = "data/world_map_collision.json"
CELL = 4

# Name plaques (the dark labels on each place). They look like road to the colour test, so
# they are made solid by hand: x0, y0, x1, y1.
PLAQUES = [
    # This map's plaques.
    (230, 215, 362, 250),   # Temple
    (808, 150, 965, 186),   # Forest
    (1405, 180, 1545, 215), # Viewpoint
    (248, 375, 372, 410),   # Lake
    (606, 400, 733, 437),   # Home
    (932, 402, 1090, 440),  # Greenhouse
    (1312, 402, 1425, 440), # Farm
    (230, 612, 375, 650),   # Library
    (1305, 592, 1452, 628), # Riverbank
    (432, 826, 562, 862),   # Beach
    (1148, 806, 1297, 845), # College
    # Earlier maps' plaques, in case they sit on the road shapes.
    (228, 92, 352, 128),    # Temple
    (792, 92, 958, 132),    # Forest
    (1395, 92, 1545, 128),  # Viewpoint
    (235, 303, 352, 340),   # Lake
    (603, 300, 727, 338),   # Home
    (922, 300, 1088, 338),  # Greenhouse
    (1305, 300, 1423, 338), # Farm
    (233, 508, 372, 545),   # Library
    (730, 503, 862, 540),   # Town
    (1300, 540, 1422, 578), # Riverbank
    (392, 718, 528, 755),   # Beach
    (1252, 718, 1390, 755), # College
]

# Walkable areas that are not road: the Town plaza, the beach sand and the beach path.
CARVE = [
    (515, 548, 510, 130),   # Town plaza
    (300, 740, 480, 130),   # beach sand
    (240, 725, 95, 175),    # beach path down from the road
    (760, 668, 40, 42),     # the gap in the plaza's south edge, onto the road
    (212, 745, 128, 90),    # open ground in front of the lighthouse
]


def road_mask(im):
    r, g, b = im[..., 0], im[..., 1], im[..., 2]
    mx = im.max(-1)
    mn = im.min(-1)
    return (mx - mn < 22) & (mx > 55) & (mx < 150)


def dilate(mask, k=2):
    out = mask.copy()
    for dy in range(-k, k + 1):
        for dx in range(-k, k + 1):
            out |= np.roll(np.roll(mask, dy, axis=0), dx, axis=1)
    return out


def majority(mask, k):
    """A cell becomes solid only if most of its neighbourhood is solid."""
    pad = np.pad(mask.astype(np.int32), k // 2, mode="edge")
    acc = np.zeros(mask.shape, np.int32)
    for dy in range(k):
        for dx in range(k):
            acc += pad[dy:dy + mask.shape[0], dx:dx + mask.shape[1]]
    return acc * 2 > k * k


def merge_rects(grid):
    h, w = grid.shape
    used = np.zeros_like(grid, bool)
    rects = []
    for y in range(h):
        x = 0
        while x < w:
            if grid[y, x] and not used[y, x]:
                x1 = x
                while x1 < w and grid[y, x1] and not used[y, x1]:
                    x1 += 1
                y1 = y + 1
                while y1 < h and all(grid[y1, x:x1]) and not any(used[y1, x:x1]):
                    y1 += 1
                used[y:y1, x:x1] = True
                rects.append((x, y, x1 - x, y1 - y))
                x = x1
            else:
                x += 1
    return rects


def main():
    im = np.asarray(Image.open(MAP).convert("RGB")).astype(int)
    h, w = im.shape[:2]
    # Widen the roads a little so the character body fits along them.
    walk = dilate(road_mask(im), 6)
    for x0, y0, cw, ch in CARVE:
        walk[y0:y0 + ch, x0:x0 + cw] = True
    for x0, y0, x1, y1 in PLAQUES:
        walk[y0:y1, x0:x1] = False
    # Lanes into the Town plaza from the road, beside the Town plaque (applied after it).
    for x0, y0, cw, ch in [(862, 600, 22, 110)]:
        walk[y0:y0 + ch, x0:x0 + cw] = True
    solid = ~walk

    ch_n, cw_n = h // CELL, w // CELL
    cells = solid[:ch_n * CELL, :cw_n * CELL].reshape(ch_n, CELL, cw_n, CELL).mean(axis=(1, 3)) > 0.5
    cells = majority(cells, 3)  # drop single-cell specks so they do not block the roads

    rects = merge_rects(cells)
    solids = [{"id": f"solid_{i}", "rect": [x * CELL, y * CELL, cwid * CELL, chei * CELL]}
              for i, (x, y, cwid, chei) in enumerate(rects)]
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({
            "_note": "Solid areas of the town map (assets/map/town_map.webp), in image pixels. Generated by scripts/gen_world_map_collision.py. Roads, the Town plaza, the beach sand and the beach path are walkable.",
            "solids": solids,
        }, f)
    print(f"{len(solids)} solid rectangles written to {OUT}")


if __name__ == "__main__":
    main()
